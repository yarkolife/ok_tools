#!/bin/bash
# Команды для чистого теста скриптов установки

echo "=========================================="
echo "Шаг 1: Остановка и удаление контейнеров"
echo "=========================================="
cd ~/docker/ok_tools_production
docker compose down
echo "✓ Контейнеры остановлены и удалены"

echo ""
echo "=========================================="
echo "Шаг 2: Удаление старых директорий"
echo "=========================================="
cd ~/docker
rm -rf ok_tools ok_tools_production
echo "✓ Директории ok_tools и ok_tools_production удалены"

echo ""
echo "=========================================="
echo "Шаг 3: Клонирование проекта из git"
echo "=========================================="
git clone https://github.com/yarkolife/ok_tools.git -b version_3 ok_tools
cd ok_tools
echo "✓ Проект клонирован"

echo ""
echo "=========================================="
echo "Шаг 4: Запуск установки"
echo "=========================================="
sudo bash deployment/scripts/install.sh

echo ""
echo "=========================================="
echo "Готово! Теперь проверь работу проекта."
echo "=========================================="
